def main():
    os.makedirs(OUT, exist_ok=True)
    g1, g2 = [], []
    for p in P:
        g1.append({"profile_id": p["pid"], "business_name": p["name"], "description": p["desc"],
                   "query": p["desc"] + SUFFIX, "profile": p["profile"], "difficulty": p["diff"],
                   "tags": p["tags"], "source": p["source"]})
        best = {}
        for idx, grade, why in p["labels"]:
            if grade <= 0:
                continue
            r = corpus[idx]
            key = (r["parent_policy_name"], r["incentive_name"])
            if key not in best or grade > best[key][0]:
                best[key] = (grade, why)
        for (par, inc), (grade, why) in sorted(best.items(), key=lambda kv: (-kv[1][0], kv[0])):
            assert len(why.split()) <= 20, (p["pid"], why)
            g2.append({"profile_id": p["pid"], "parent_policy_name": par, "incentive_name": inc,
                       "relevance": grade, "rationale": why})
    with open(os.path.join(OUT, "g1_profiles.jsonl"), "w", encoding="utf-8", newline="\n") as f:
        for o in g1:
            f.write(json.dumps(o, ensure_ascii=False) + "\n")
    with open(os.path.join(OUT, "g2_relevance.jsonl"), "w", encoding="utf-8", newline="\n") as f:
        for o in g2:
            f.write(json.dumps(o, ensure_ascii=False) + "\n")
    print(len(g1), "profiles", len(g2), "labels")


if __name__ == "__main__":
    main()
